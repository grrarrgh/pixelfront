LINE_H = 7
_cache = {}


def _glyph(ch, color, scale):
    key = (ch, color, scale)
    surf = _cache.get(key)
    if surf is None:
        rows = _GLYPHS.get(ch) or _GLYPHS["?"]
        surf = pygame.Surface((len(rows[0]), 5), pygame.SRCALPHA)
        for y, row in enumerate(rows):
            for x, c in enumerate(row):
                if c == "#":
                    surf.set_at((x, y), color)
        if scale != 1:
            surf = pygame.transform.scale(surf, (surf.get_width() * scale, 5 * scale))
        _cache[key] = surf
    return surf


def text_width(text, scale=1):
    w = 0
    for ch in text.upper():
        w += len((_GLYPHS.get(ch) or _GLYPHS["?"])[0]) + 1
    return max(0, w - 1) * scale


def draw_text(surf, text, x, y, color=(255, 255, 255), shadow=(0, 0, 0), scale=1, align="left"):
    text = text.upper()
    if align == "center":
        x -= text_width(text, scale) // 2
    elif align == "right":
        x -= text_width(text, scale)
    color = tuple(color)
    if shadow:
        _draw(surf, text, x + scale, y + scale, tuple(shadow), scale)
    return _draw(surf, text, x, y, color, scale)


def _draw(surf, text, x, y, color, scale):
    cx = x
    for ch in text:
        g = _glyph(ch, color, scale)
        surf.blit(g, (cx, y))
        cx += g.get_width() + scale
    return cx - x
